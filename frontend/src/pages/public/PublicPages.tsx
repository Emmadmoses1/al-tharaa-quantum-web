export function FaqPage() {
  const [open, setOpen] = useState<number | null>(0)
  return (
    <PublicShell title="الأسئلة الشائعة">
      {FAQ.map(([q, a], i) => (
        <div key={i} className="glass-card" style={{ marginBottom: 10, overflow: 'hidden' }}>
          <button onClick={() => setOpen(open === i ? null : i)} aria-expanded={open === i} style={{
            width: '100%', display: 'flex', justifyContent: 'space-between', alignItems: 'center', gap: 12, textAlign: 'right',
            background: 'none', border: 'none', cursor: 'pointer', padding: '16px 18px', minHeight: 54,
            color: '#fff', fontFamily: 'Cairo', fontSize: 15, fontWeight: 700,
          }}>
            <span>{q}</span>
            <ChevronDown size={18} color="#D4AF37" style={{ flexShrink: 0, transform: open === i ? 'rotate(180deg)' : 'none', transition: 'transform .2s' }} />
          </button>
          {open === i && <div style={{ padding: '0 18px 18px', fontSize: 14, color: 'rgba(255,255,255,0.65)', fontFamily: 'Cairo', lineHeight: 2 }}>{a}</div>}
        </div>
      ))}
      <Notice color="#D4AF37">لم تجد جوابك؟ <Link to="/contact" style={{ color: '#D4AF37' }}>تواصل معنا</Link>.</Notice>
    </PublicShell>
  )
}

